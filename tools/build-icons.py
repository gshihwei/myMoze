#!/usr/bin/env python3
"""Build the built-in account icons.

Source of truth: images/<bank>/<name>.(png|jpg|jpeg|webp)
  images/<bank>/<bank>.*   -> the bank's own icon
  images/<bank>/<other>.*  -> a credit card (or other product) of that bank
  images/aliases.json      -> optional { "<name>": ["關鍵字", ...] }; the file name itself is always a keyword
Output: icons/banks/<bank>/<name>.webp (128px, centred on transparent square),
        js/icon-manifest.js (ACCT_ICON_MANIFEST), and the ICON_ASSETS line in sw.js.
Only new or changed images are converted (state in images/.converted.json, by content hash).
Run:  python tools/build-icons.py          convert what is new/changed, then rebuild the manifest
      python tools/build-icons.py --list   just list the images that are not converted yet
      python tools/build-icons.py --all    convert everything again
then: node tools/build-bundle.js
"""
import hashlib, json, os, re, shutil, sys
from PIL import Image
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
os.chdir(root)
SRC, OUT, SIZE = 'images', 'icons/banks', 128
EXT = ('.png', '.jpg', '.jpeg', '.webp')
aliases = json.load(open(f'{SRC}/aliases.json', encoding='utf-8')) if os.path.exists(f'{SRC}/aliases.json') else {}
LIST, ALL = '--list' in sys.argv, '--all' in sys.argv
STATE = f'{SRC}/.converted.json'
done = json.load(open(STATE)) if os.path.exists(STATE) and not ALL else {}
entries, seen, pending, newdone = [], {}, [], {}
for bank in sorted(d for d in os.listdir(SRC) if os.path.isdir(f'{SRC}/{d}')):
    if not LIST: os.makedirs(f'{OUT}/{bank}', exist_ok=True)
    for f in sorted(os.listdir(f'{SRC}/{bank}')):
        stem, ext = os.path.splitext(f)
        if ext.lower() not in EXT: continue
        if stem in seen: sys.exit(f'duplicate name "{stem}": {seen[stem]} and {bank}')
        seen[stem] = bank
        h = hashlib.sha1(open(f'{SRC}/{bank}/{f}', 'rb').read()).hexdigest(); out = f'{OUT}/{bank}/{stem}.webp'
        newdone[f'{bank}/{f}'] = h
        if done.get(f'{bank}/{f}') == h and os.path.exists(out): pass
        else:
            pending.append(f'{bank}/{f}')
            if not LIST:
                im = Image.open(f'{SRC}/{bank}/{f}').convert('RGBA')
                side = max(im.size); c = Image.new('RGBA', (side, side), (0, 0, 0, 0)); c.alpha_composite(im, ((side - im.width) // 2, (side - im.height) // 2))
                c.resize((SIZE, SIZE), Image.LANCZOS).save(out, 'WEBP', quality=92, method=6)
        kw = []
        for k in [stem] + list(aliases.get(stem, [])):
            k = re.sub(r'\s+', ' ', str(k).lower()).strip()
            if k and k not in kw: kw.append(k)
        entries.append({'b': bank, 'n': stem, 'k': kw, 'bank': 1 if stem == bank else 0})
if LIST:
    print(f'{len(pending)} 張尚未轉換：' if pending else '沒有未轉換的圖片')
    for x in pending: print('  ' + x)
    sys.exit(0)
keep = {f'{e["b"]}/{e["n"]}.webp' for e in entries}
for b in os.listdir(OUT):
    if os.path.isdir(f'{OUT}/{b}'):
        for f in os.listdir(f'{OUT}/{b}'):
            if f'{b}/{f}' not in keep: os.remove(f'{OUT}/{b}/{f}'); print('removed orphan', f'{b}/{f}')
        if not os.listdir(f'{OUT}/{b}'): os.rmdir(f'{OUT}/{b}')
json.dump(newdone, open(STATE, 'w'), indent=1)
open('js/icon-manifest.js', 'w', encoding='utf-8', newline='\n').write(
    '// GENERATED by tools/build-icons.py from images/ — do not edit by hand.\nvar ACCT_ICON_MANIFEST=' + json.dumps(entries, ensure_ascii=False, separators=(',', ':')) + ';\n')
sw = open('sw.js', encoding='utf-8').read()
assets = ','.join(f"'./icons/banks/{e['b']}/{e['n']}.webp'" for e in entries)
line = f'const ICON_ASSETS=[{assets}];'
sw = re.sub(r'const ICON_ASSETS=\[[^\n]*\];', lambda m: line, sw) if 'const ICON_ASSETS=' in sw else sw.replace('const ASSETS=', line + '\nconst ASSETS=', 1)
open('sw.js', 'w', encoding='utf-8', newline='').write(sw)
print(f'{len(entries)} icons, {len(set(e["b"] for e in entries))} banks; converted now: {len(pending)}' + (' -> ' + ', '.join(pending) if pending else ''))
